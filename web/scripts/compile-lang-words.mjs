// compile-lang-words.mjs — compile the three locale names ("中文",
// "English", "Español") into SVG path data for the morphing language
// label. Run after changing the font or the words:
//
//   npm run build:words
//
// The output (src/i18n/lang-words.js) is committed, so fontkit and the
// font are only needed when regenerating. Font: STHeiti SC Medium
// (macOS system font, so regeneration currently needs a Mac).
//   Why not Noto Sans SC: its CJK glyphs are built from overlapping
//   components, and the label renders with fill-rule evenodd (morphicons
//   may flip a subpath's winding mid-flight, so the fill rule must be
//   direction-agnostic) — evenodd cancels overlaps and punches white
//   patches at stroke junctions. STHeiti's contours don't overlap.
//
// Gotchas baked in (learned in the spike):
// - fontkit path transforms are immutable — assign the return value;
// - fontkit paths are y-up, SVG is y-down — hence scale(s, -s);
// - words are x-normalised (minX = 0) so the viewBox can't clip.

import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const fontkit = createRequire(import.meta.url)("fontkit");

const root = path.dirname(fileURLToPath(import.meta.url));
const FONT = "/System/Library/Fonts/STHeiti Medium.ttc";
const OUT = path.join(root, "../src/i18n/lang-words.js");

/* label cap height in px — the paths render 1:1 in the switcher */
const TARGET = 14;

const font = fontkit.openSync(FONT, "STHeitiSC-Medium");
const scale = TARGET / font.unitsPerEm;

function wordData(word) {
  const run = font.layout(word);
  let x = 0;
  const paths = [];
  for (let i = 0; i < run.glyphs.length; i++) {
    const g = run.glyphs[i];
    const p = run.positions[i];
    if (g.path.commands.length) {
      paths.push(
        g.path
          .scale(scale, -scale)
          .translate((x + (p.xOffset || 0)) * scale, -(p.yOffset || 0) * scale),
      );
    }
    x += p.xAdvance || 0;
  }
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const tp of paths) {
    const b = tp.bbox;
    minX = Math.min(minX, b.minX);
    minY = Math.min(minY, b.minY);
    maxX = Math.max(maxX, b.maxX);
    maxY = Math.max(maxY, b.maxY);
  }
  const d = paths.map((tp) => tp.translate(-minX, 0).toSVG()).join(" ");
  const round = (n) => Math.round(n * 100) / 100;
  return { d, w: round(maxX - minX), minY: round(minY), h: round(maxY - minY) };
}

const words = {
  zh: wordData("中文"),
  en: wordData("English"),
  es: wordData("Español"),
};

const banner = `/* generated by scripts/compile-lang-words.mjs — do not edit by hand.
 * Glyph outlines of the locale names (STHeiti SC Medium), baseline y=0,
 * x normalised to minX=0, ${TARGET}px cap scale. Consumed by
 * LanguageSwitcher.vue via morphicons (fill-rule: evenodd — do not
 * remove). */\n`;

fs.writeFileSync(
  OUT,
  banner + "export const LANG_WORDS = " + JSON.stringify(words, null, 2) + ";\n",
);
for (const [k, v] of Object.entries(words)) {
  console.log(k, `${v.d.length} bytes`, `w=${v.w} minY=${v.minY} h=${v.h}`);
}
